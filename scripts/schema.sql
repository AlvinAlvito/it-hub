CREATE TABLE IF NOT EXISTS users (
  id INT AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(60) NOT NULL UNIQUE,
  name VARCHAR(120) NOT NULL,
  role ENUM('superadmin','direktur') NOT NULL,
  password_hash VARCHAR(100) NOT NULL,
  pin_hash VARCHAR(100) NOT NULL,
  session_version INT NOT NULL DEFAULT 1,
  failed_logins INT NOT NULL DEFAULT 0,
  locked_until DATETIME NULL,
  failed_pins INT NOT NULL DEFAULT 0,
  pin_locked_until DATETIME NULL,
  last_login DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS webs (
  id INT AUTO_INCREMENT PRIMARY KEY,
  slug VARCHAR(80) NOT NULL UNIQUE,
  name VARCHAR(120) NOT NULL,
  url VARCHAR(255) NULL,
  category VARCHAR(60) NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'aktif',
  summary TEXT NULL,
  fungsi TEXT NULL,
  cara_pakai TEXT NULL,
  repo VARCHAR(255) NULL,
  tech VARCHAR(255) NULL,
  sort INT NOT NULL DEFAULT 0,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS web_media (
  id INT AUTO_INCREMENT PRIMARY KEY,
  web_id INT NOT NULL,
  type ENUM('image','video','youtube') NOT NULL,
  path VARCHAR(255) NOT NULL,
  caption VARCHAR(255) NULL,
  sort INT NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX (web_id),
  FOREIGN KEY (web_id) REFERENCES webs(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS web_updates (
  id INT AUTO_INCREMENT PRIMARY KEY,
  web_id INT NOT NULL,
  date DATE NOT NULL,
  title VARCHAR(255) NOT NULL,
  detail TEXT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX (web_id),
  FOREIGN KEY (web_id) REFERENCES webs(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS web_accounts (
  id INT AUTO_INCREMENT PRIMARY KEY,
  web_id INT NOT NULL,
  role_name VARCHAR(120) NOT NULL,
  username VARCHAR(190) NULL,
  password_enc TEXT NULL,
  fungsi TEXT NULL,
  holder VARCHAR(120) NULL,
  login_url VARCHAR(255) NULL,
  note TEXT NULL,
  sort INT NOT NULL DEFAULT 0,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX (web_id),
  FOREIGN KEY (web_id) REFERENCES webs(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS projects (
  id INT AUTO_INCREMENT PRIMARY KEY,
  slug VARCHAR(80) NOT NULL UNIQUE,
  name VARCHAR(160) NOT NULL,
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  category VARCHAR(20) NOT NULL DEFAULT 'internal',
  status VARCHAR(20) NOT NULL DEFAULT 'rencana',
  progress INT NOT NULL DEFAULT 0,
  masalah TEXT NULL,
  solusi TEXT NULL,
  tujuan TEXT NULL,
  manfaat TEXT NULL,
  output TEXT NULL,
  repos VARCHAR(255) NULL,
  sort INT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS project_tasks (
  id INT AUTO_INCREMENT PRIMARY KEY,
  project_id INT NOT NULL,
  title VARCHAR(255) NOT NULL,
  start_date DATE NULL,
  end_date DATE NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'belum',
  sort INT NOT NULL DEFAULT 0,
  INDEX (project_id),
  FOREIGN KEY (project_id) REFERENCES projects(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS activities (
  id INT AUTO_INCREMENT PRIMARY KEY,
  date DATE NOT NULL,
  title VARCHAR(255) NOT NULL,
  detail TEXT NULL,
  category VARCHAR(30) NOT NULL DEFAULT 'koordinasi',
  duration_min INT NULL,
  project_id INT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX (date),
  FOREIGN KEY (project_id) REFERENCES projects(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS commits (
  sha CHAR(40) PRIMARY KEY,
  repo VARCHAR(120) NOT NULL,
  message TEXT NOT NULL,
  author VARCHAR(120) NULL,
  committed_at DATETIME NOT NULL,
  url VARCHAR(255) NULL,
  INDEX (committed_at),
  INDEX (repo)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS summaries (
  id INT AUTO_INCREMENT PRIMARY KEY,
  period_type VARCHAR(10) NOT NULL,
  period_key VARCHAR(30) NOT NULL,
  content MEDIUMTEXT NOT NULL,
  source_count INT NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY (period_type, period_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS audit_log (
  id INT AUTO_INCREMENT PRIMARY KEY,
  user_id INT NULL,
  action VARCHAR(60) NOT NULL,
  target VARCHAR(255) NULL,
  ip VARCHAR(64) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS settings (
  k VARCHAR(60) PRIMARY KEY,
  v TEXT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
